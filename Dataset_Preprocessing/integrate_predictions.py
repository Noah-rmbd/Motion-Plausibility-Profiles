import json
import pickle
import os

def integrate_predictions_into_json(json_file, pkl_file, model_name=None):
    """
    Integrates LSTM prediction results (anomalies) from a pickle file into the 
    preprocessed JSON files (trajectories and transitions) used by the web visualization.

    Parameters:
    - json_file (str): Path to the JSON file containing the list of trajectories (e.g. trajectories_list.json)
    - pkl_file (str): Path to the pickle file containing anomaly scores (e.g. anomaly_scores_inat.pkl)
    - model_name (str): Optional string. If provided, JSON keys are suffixed with _{model_name}.
    """
    
    key_unplausible = f"is_unplausible_{model_name}" if model_name else "is_unplausible"
    key_error = f"reconstruction_error_{model_name}" if model_name else "reconstruction_error"
    key_features = f"reconstruction_feature_errors_{model_name}" if model_name else "reconstruction_feature_errors"
    
    # 1. Verification of file existence
    if not os.path.exists(json_file) or not os.path.exists(pkl_file):
        print(f"Skipping {json_file} as files are missing.")
        return
        
    # 2. Load anomaly scores generated by the LSTM prediction script
    print(f"Loading {pkl_file}...")
    scores = []
    with open(pkl_file, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            obj = json.loads(line)
            if 'metadata' in obj:
                continue
            scores.append(obj)
        
    # 3. Create a mapping for trajectories: trajectory_id -> anomaly info
    # The trajectory_id in the pickle is a list/tuple, so we take the first element (the ID) as key.
    scores_dict = {
        (s['trajectory_id'] if isinstance(s['trajectory_id'], int) else s['trajectory_id'][0]): {
            'is_unplausible': s['is_unplausible'],
            'reconstruction_error': s['reconstruction_error']
        }
        for s in scores
    }
    
    # 4. Create a mapping for transitions: transition_id -> transition anomaly info
    # This helps identify which specific transitions within an unplausible trajectory 
    # were responsible for the high reconstruction error.
    trans_anomaly_map = {}
    for s in scores:
        is_traj_unplausible = s['is_unplausible']
        worst_trans_id = s.get('least_plausible_transition_id')
        step_errors = s.get('transition_errors', {})
        
        step_feature_errors = s.get('transition_feature_errors', {})
        
        for trans_id, step_err in step_errors.items():
            # A transition is flagged as unplausible in the UI if:
            # - The parent trajectory itself is classified as unplausible by the LSTM model
            # - AND this specific transition has the highest reconstruction error (least plausible) in that trajectory
            trans_id_int = int(trans_id)
            is_trans_unplausible = is_traj_unplausible and (worst_trans_id is not None and trans_id_int == int(worst_trans_id))
            trans_anomaly_map[trans_id_int] = {
                'is_unplausible': is_trans_unplausible,
                'reconstruction_error': step_err,
                'reconstruction_feature_errors': step_feature_errors.get(str(trans_id), step_feature_errors.get(trans_id_int, [0.0]*6))
            }
    
    # 5. Load and update the trajectories JSON list
    print(f"Loading {json_file}...")
    with open(json_file, 'r') as f:
        trajectories = json.load(f)
        
    print("Updating trajectories...")
    for t in trajectories:
        tid = t['trajectory_id']
        if tid in scores_dict:
            # Inject LSTM prediction results into the trajectory object
            t[key_unplausible] = scores_dict[tid]['is_unplausible']
            t[key_error] = scores_dict[tid]['reconstruction_error']
        else:
            # Default values for trajectories not evaluated or not present in the model output
            t[key_unplausible] = False
            t[key_error] = 0.0
            
    print(f"Saving {json_file}...")
    with open(json_file, 'w') as f:
        json.dump(trajectories, f, indent=4)
        
    # 6. Load and update the corresponding transitions JSON list
    # The transitions file is expected to be in the same folder, with a matching name pattern
    trans_file = json_file.replace("trajectories_list", "transitions_list")
    if os.path.exists(trans_file):
        print(f"Loading {trans_file}...")
        with open(trans_file, 'r') as f:
            transitions = json.load(f)
            
        print("Updating transitions...")
        for trans in transitions:
            trans_id = trans['transition_id']
            if trans_id in trans_anomaly_map:
                # Inject LSTM prediction results into the transition object
                trans[key_unplausible] = trans_anomaly_map[trans_id]['is_unplausible']
                trans[key_error] = trans_anomaly_map[trans_id]['reconstruction_error']
                trans[key_features] = trans_anomaly_map[trans_id]['reconstruction_feature_errors']
            else:
                # Default values for transitions not evaluated or not present in the model output
                trans[key_unplausible] = False
                trans[key_error] = 0.0
                trans[key_features] = [0.0]*6
                
        print(f"Saving {trans_file}...")
        with open(trans_file, 'w') as f:
            json.dump(transitions, f, indent=4)
        
    print("Done.\n")

if __name__ == "__main__":
    # Main execution: Process both iNaturalist and Gowalla datasets
    integrate_predictions_into_json(
        "Preprocessed_Dataset/trajectories_list.json", 
        "Models_weights_and_results/anomaly_scores_inat.jsonl"
    )
    integrate_predictions_into_json(
        "Preprocessed_Dataset/gowalla_trajectories_list.json", 
        "Models_weights_and_results/anomaly_scores_gowallav3.jsonl"
    )
